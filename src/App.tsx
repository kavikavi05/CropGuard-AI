      doc.setFontSize(14);
      doc.setTextColor(30, 41, 59);
      doc.text(`${t('pdfTreatment')}:`, margin, y);
      y += 5;
      doc.setFontSize(11);
      doc.setTextColor(51, 65, 85);
      const solutionLines = doc.splitTextToSize(data.solution.replace(/[*]/g, '•').replace(/[#`]/g, ''), pageWidth - (margin * 2));
      solutionLines.forEach((line: string) => {
        if (y + 7 > doc.internal.pageSize.getHeight() - 20) {
          doc.addPage();
          y = 20;
        }
        doc.text(line, margin, y);
        y += 6;
        if (line.trim().startsWith('•')) y += 2; // Extra space after each point
      });
      y += 10;

      doc.setFontSize(14);
      doc.setTextColor(30, 41, 59);
      doc.text(`${t('pdfAnalysisDetails')}:`, margin, y);
      y += 5;
      doc.setFontSize(10);
      doc.setTextColor(71, 85, 105);
      const detailLines = doc.splitTextToSize(data.details.replace(/[*]/g, '•').replace(/[#`]/g, ''), pageWidth - (margin * 2));
