      y += 7;

      try {
        const highlightedImg = await getHighlightedImage(img, data);
        const imgProps = doc.getImageProperties(highlightedImg);
        const imgWidth = pageWidth - (margin * 2);
        const imgHeight = (imgProps.height * imgWidth) / imgProps.width;
        const maxHeight = 80;
        const finalImgHeight = Math.min(imgHeight, maxHeight);
        const finalImgWidth = (imgProps.width * finalImgHeight) / imgProps.height;
        doc.addImage(highlightedImg, 'JPEG', margin + (imgWidth - finalImgWidth) / 2, y, finalImgWidth, finalImgHeight);
        y += finalImgHeight + 8;
      } catch (e) {
        y += 10;
      }

      doc.setFontSize(14);
      doc.setTextColor(30, 41, 59);
      doc.text(`${t('pdfDiagnosis')}:`, margin, y);
